/**
 * TradeCraft AI — High-Frequency Market Making & Optimal Avellaneda-Stoikov
 * Inventory Control Engine
 * Type Definitions & Data Contracts (Sprint 26)
 *
 * Covers:
 * 1. Avellaneda-Stoikov mathematical parameters (midprice, inventory, risk aversion,
 *    volatility, time horizon, order book liquidity decay kappa, arrival intensity A).
 * 2. Optimal bid/ask quotes, reservation price, asymmetric half-spreads, inventory skews.
 * 3. Market Maker state tracking (cash, inventory, realized/unrealized PnL,
 *    spread capture vs. inventory drift / depreciation decomposition).
 * 4. Microsecond/Tick simulation steps with Poisson fill arrivals and order execution.
 * 5. 1-Click Inventory Control Actions (FLATTEN_INVENTORY, SKEW_AGGRESSIVE,
 *    WIDEN_DEFENSIVE, RESET_STATE).
 * 6. Presets and execution configurations for Indian Index and Equity Derivatives
 *    (NIFTY 50, BANKNIFTY, RELIANCE).
 */

export type MarketMakingTicker = 'NIFTY' | 'BANKNIFTY' | 'RELIANCE' | string;

/**
 * 1-Click Inventory Control Action Types
 */
export type InventoryActionType =
  | 'FLATTEN_INVENTORY'
  | 'SKEW_AGGRESSIVE'
  | 'WIDEN_DEFENSIVE'
  | 'RESET_STATE';

/**
 * Order fill type occurred during a discrete simulation step
 */
export type FillType = 'NONE' | 'BID_FILL' | 'ASK_FILL' | 'BOTH_FILL';

/**
 * Avellaneda-Stoikov Model Parameters
 *
 * Formulations:
 * - Midprice process: dS_t = sigma * dW_t
 * - Reservation / Indifference Price: r(s, q, t) = s - q * gamma * sigma^2 * (T - t)
 * - Optimal Spread: s*(s, q, t) = (2 / gamma) * ln(1 + gamma / kappa)
 * - Order Arrival Intensities: lambda_a(delta_a) = A * exp(-kappa * delta_a)
 *                              lambda_b(delta_b) = A * exp(-kappa * delta_b)
 */
export interface AvellanedaStoikovParams {
  /** Current underlying midprice (s) */
  s: number;
  /** Current inventory position in units / lots (q) */
  q: number;
  /** Risk aversion parameter (gamma > 0), e.g. 0.01 to 0.5 */
  gamma: number;
  /** Volatility of underlying asset (sigma > 0) in annualized or normalized units */
  sigma: number;
  /** Total time horizon of market making session (T, e.g. 1.0 or minutes) */
  T: number;
  /** Current elapsed time (0 <= t <= T) */
  t: number;
  /** Order book liquidity parameter / depth decay elasticity (kappa > 0) */
  kappa: number;
  /** Order arrival intensity multiplier (A > 0) */
  A: number;
  /** Maximum allowable absolute inventory before hard quote suppression (|q| <= maxInventory) */
  maxInventory: number;
  /** Minimum allowable tick size for the instrument (e.g. 0.05 for NSE) */
  tickSize: number;
  /** Standard contract lot size (e.g. 25 for NIFTY, 15 for BANKNIFTY, 1 for Equity) */
  lotSize: number;
}

/**
 * Market Maker Quotes generated by the Avellaneda-Stoikov Engine
 */
export interface MarketMakerQuotes {
  /** Indifference / reservation price: r(s, q, t) = s - q * gamma * sigma^2 * (T - t) */
  reservationPrice: number;
  /** Total optimal spread: delta_a + delta_b */
  optimalSpread: number;
  /** Optimal active Bid price (rounded to tickSize, null if suppressed by maxInventory) */
  bidPrice: number | null;
  /** Optimal active Ask price (rounded to tickSize, null if suppressed by -maxInventory) */
  askPrice: number | null;
  /** Distance of bid price from midprice: delta_b = s - bidPrice */
  halfSpreadBid: number;
  /** Distance of ask price from midprice: delta_a = askPrice - s */
  halfSpreadAsk: number;
  /** Asymmetric skew on the bid quote due to inventory (delta_b - symmetricHalfSpread) */
  bidSkew: number;
  /** Asymmetric skew on the ask quote due to inventory (delta_a - symmetricHalfSpread) */
  askSkew: number;
  /** Total inventory penalty shift: q * gamma * sigma^2 * (T - t) */
  inventoryPenalty: number;
  /** Theoretical unrounded reservation price */
  rawReservationPrice: number;
  /** Theoretical unrounded bid price */
  rawBidPrice: number;
  /** Theoretical unrounded ask price */
  rawAskPrice: number;
  /** Instantaneous Poisson arrival intensity for bid: lambda_b = A * exp(-kappa * delta_b) */
  bidArrivalRate: number;
  /** Instantaneous Poisson arrival intensity for ask: lambda_a = A * exp(-kappa * delta_a) */
  askArrivalRate: number;
  /** Probability of bid fill over unit step delta_t */
  bidFillProbability: number;
  /** Probability of ask fill over unit step delta_t */
  askFillProbability: number;
  /** Flag indicating whether bid order is suppressed due to reaching maxInventory */
  isBidSuppressed: boolean;
  /** Flag indicating whether ask order is suppressed due to reaching -maxInventory */
  isAskSuppressed: boolean;
}

/**
 * Single executed trade fill in the market maker session
 */
export interface FillEvent {
  id: string;
  step: number;
  timestamp: number;
  timeString: string;
  side: 'BUY' | 'SELL';
  price: number;
  quantity: number;
  lotSize: number;
  inventoryBefore: number;
  inventoryAfter: number;
  cashAfter: number;
  spreadCaptured: number;
  midPriceAtFill: number;
  executionFee: number;
}

/**
 * Market Maker Real-Time Account & Risk State
 */
export interface MarketMakerState {
  /** Accumulated cash balance in ₹ */
  cash: number;
  /** Current net inventory position (positive = long, negative = short) */
  inventory: number;
  /** Realized profit & loss from closed trades in ₹ */
  realizedPnL: number;
  /** Unrealized mark-to-market P&L on remaining inventory at current midprice in ₹ */
  unrealizedPnL: number;
  /** Total P&L = realizedPnL + unrealizedPnL */
  totalPnL: number;
  /** Cumulative P&L generated strictly from capturing the bid-ask spread */
  spreadCapturePnL: number;
  /** Cumulative P&L drift caused by inventory price depreciation / adverse selection */
  inventoryDepreciationPnL: number;
  /** Total exchange & statutory transaction charges incurred */
  totalFees: number;
  /** Chronological history of all executed fills */
  fillHistory: FillEvent[];
  /** Total number of fills executed */
  totalFills: number;
  /** Total buy fills executed */
  buyFills: number;
  /** Total sell fills executed */
  sellFills: number;
  /** Peak positive inventory reached during session */
  peakInventory: number;
  /** Trough negative inventory reached during session */
  troughInventory: number;
  /** Maximum drawdown experienced during session in ₹ */
  maxDrawdown: number;
  /** Peak total P&L reached */
  highWaterMark: number;
}

/**
 * Record of a discrete simulation step in the Avellaneda-Stoikov trajectory
 */
export interface QuoteSimulationStep {
  /** Step sequence index (0 to N) */
  step: number;
  /** Timestamp (epoch ms) */
  timestamp: number;
  /** Formatted time string (HH:mm:ss) */
  timeString: string;
  /** Underlying midprice at this step */
  midPrice: number;
  /** Indifference reservation price */
  reservationPrice: number;
  /** Active market maker bid quote (null if suppressed) */
  bidQuote: number | null;
  /** Active market maker ask quote (null if suppressed) */
  askQuote: number | null;
  /** Current inventory held by the MM after fills in this step */
  inventory: number;
  /** Fill type observed in this step */
  fillType: FillType;
  /** Total PnL at this step in ₹ */
  pnl: number;
  /** Spread capture component of PnL */
  spreadCapturePnL: number;
  /** Inventory depreciation / adverse drift component of PnL */
  inventoryDepreciationPnL: number;
  /** Cash balance at this step */
  cash: number;
  /** Active bid half-spread (s - bidQuote) */
  bidSpread: number;
  /** Active ask half-spread (askQuote - s) */
  askSpread: number;
  /** Total quoted spread (askQuote - bidQuote) */
  totalSpread: number;
  /** Probability of bid execution in this step */
  bidProb: number;
  /** Probability of ask execution in this step */
  askProb: number;
}

